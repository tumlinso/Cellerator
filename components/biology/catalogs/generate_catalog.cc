#include <Cellerator/biology/gene_annotation.hh>

#include <filesystem>
#include <fstream>
#include <iostream>
#include <map>
#include <set>
#include <stdexcept>
#include <string>
#include <string_view>
#include <vector>

namespace bio = cellerator::biology;
namespace {

struct Gene {
    std::string_view symbol;
    std::set<std::string_view> aliases;
    uint32_t index = 0;
};

using Genes = std::map<std::string_view, Gene>;

struct Subset {
    std::string name;
    std::vector<uint32_t> indices;
};

std::string_view text(bio::AnnotationText text) {
    return text.size ? std::string_view(text.data, text.size) : std::string_view{};
}

Genes collect_genes(bio::GeneCatalog catalog) {
    Genes genes;
    for (size_t i = 0; i < catalog.count; ++i) {
        const auto &row = catalog.records[i];
        auto &gene = genes[text(row.id)];
        const auto symbol = text(row.symbol);
        if (!gene.symbol.empty() && !symbol.empty() && gene.symbol != symbol)
            throw std::runtime_error("conflicting symbols for " + std::string(text(row.id)));
        if (gene.symbol.empty()) gene.symbol = symbol;
        for (size_t a = 0; a < row.alias_count; ++a)
            gene.aliases.insert(text(row.aliases[a]));
    }
    if (genes.size() > UINT32_MAX) throw std::runtime_error("too many catalog rows for subset indices");
    uint32_t index = 0;
    for (auto &entry : genes) entry.second.index = index++;
    return genes;
}

Subset read_subset(const std::filesystem::path &path, const Genes &genes) {
    Subset subset{path.stem().string(), {}};
    std::ifstream input(path);
    if (!input) throw std::runtime_error("cannot open subset " + path.string());
    std::set<uint32_t> seen;
    for (std::string id; std::getline(input, id);) {
        if (id.ends_with('\r')) id.pop_back();
        if (id.empty() || id.front() == '#') continue;
        const auto gene = genes.find(id);
        if (gene == genes.end())
            throw std::runtime_error(path.string() + ": unknown gene ID " + id);
        const auto index = gene->second.index;
        if (!seen.insert(index).second)
            throw std::runtime_error(path.string() + ": duplicate gene ID " + id);
        subset.indices.push_back(index);
    }
    if (input.bad() || subset.indices.empty())
        throw std::runtime_error("cannot read a nonempty subset from " + path.string());
    return subset;
}

void literal(std::ostream &out, std::string_view value) {
    out << '"';
    for (unsigned char c : value) {
        if (c == '"' || c == '\\') out << '\\' << char(c);
        else if (c >= 32 && c <= 126) out << char(c);
        else out << '\\' << char('0'+(c >> 6)) << char('0'+((c >> 3) & 7)) << char('0'+(c & 7));
    }
    out << '"';
}

void annotation_text(std::ostream &out, std::string_view value) {
    if (value.empty()) {
        out << "{nullptr, 0}";
        return;
    }
    out << '{';
    literal(out, value);
    out << ", " << value.size() << '}';
}

void write_catalog(std::ostream &out, const Genes &genes, const std::vector<Subset> &subsets,
    const char *assembly, const char *release, const char *source) {
    out << "// Generated by Cellerator Biology. Do not edit.\n";
    size_t alias_count = 0;
    for (const auto &entry : genes) alias_count += entry.second.aliases.size();
    if (alias_count) {
        out << "constexpr AnnotationText aliases[]{\n";
        for (const auto &entry : genes) {
            for (auto alias : entry.second.aliases) {
                out << "    ";
                annotation_text(out, alias);
                out << ",\n";
            }
        }
        out << "};\n";
    }
    out << "constexpr GeneAnnotationRecord records[]{\n";
    size_t offset = 0;
    for (const auto &[id, gene] : genes) {
        out << "    {";
        annotation_text(out, id);
        out << ", ";
        annotation_text(out, gene.symbol);
        if (gene.aliases.empty()) out << ", nullptr, 0},\n";
        else out << ", aliases + " << offset << ", " << gene.aliases.size() << "},\n";
        offset += gene.aliases.size();
    }
    out << "};\n";
    for (size_t i = 0; i < subsets.size(); ++i) {
        out << "constexpr uint32_t subset_" << i << "[]{\n";
        const auto &indices = subsets[i].indices;
        for (size_t j = 0; j < indices.size(); ++j)
            out << (j % 12 ? " " : "    ") << indices[j] << ',' << (j % 12 == 11 ? "\n" : "");
        if (indices.size() % 12) out << '\n';
        out << "};\n";
    }
    if (!subsets.empty()) {
        out << "constexpr GeneSubset subsets[]{\n";
        for (size_t i = 0; i < subsets.size(); ++i) {
            out << "    {";
            literal(out, subsets[i].name);
            out << ", subset_" << i << ", " << subsets[i].indices.size() << "},\n";
        }
        out << "};\n";
    }
    out << "constexpr BuiltinGeneCatalog builtin_catalog{\n    ";
    literal(out, assembly);
    out << ", ";
    literal(out, release);
    out << ", ";
    literal(out, source);
    out << ",\n    {records, " << genes.size() << "}, ";
    out << (subsets.empty() ? "nullptr" : "subsets") << ", " << subsets.size() << "\n};\n";
}

} // namespace

int main(int argc, char **argv) {
    if (argc < 7) {
        std::cerr << "usage: generate_catalog OUTPUT FORMAT ANNOTATION ASSEMBLY RELEASE SOURCE [SUBSET.ids ...]\n";
        return 1;
    }
    try {
        const std::string_view format(argv[2]);
        if (format != "gtf" && format != "gff3") throw std::runtime_error("expected gtf or gff3");
        bio::GeneAnnotation annotation;
        const auto error = bio::read_gene_annotation(argv[3],
            format == "gtf" ? bio::GeneAnnotationFormat::gtf : bio::GeneAnnotationFormat::gff3, annotation);
        if (error.message) {
            std::cerr << argv[3];
            if (error.line) std::cerr << ':' << error.line;
            std::cerr << ": " << error.message << '\n';
            return 1;
        }
        const auto genes = collect_genes(annotation.catalog());
        std::vector<Subset> subsets;
        std::set<std::string> names;
        for (int i = 7; i < argc; ++i) {
            auto subset = read_subset(argv[i], genes);
            if (!names.insert(subset.name).second)
                throw std::runtime_error("duplicate subset name " + subset.name);
            subsets.push_back(std::move(subset));
        }
        std::ofstream output(argv[1], std::ios::binary);
        write_catalog(output, genes, subsets, argv[4], argv[5], argv[6]);
        output.close();
        if (!output) throw std::runtime_error("cannot write catalog to " + std::string(argv[1]));
    } catch (const std::exception &error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
    return 0;
}
